# Generate Rust code
def rust_escape(s):
    return s.replace('\\', '\\\\').replace('"', '\\"')

def lifecycle_variant(s):
    return f"PartLifecycle::{s}"

def generate_match_arm(class_name, parts):
    lines = [f"            ComponentClass::{class_name} => &["]
    for mpn, mfr, lifecycle, ds in parts:
        lines.append(f"                CatalogPart {{")
        lines.append(f"                    mpn: \"{rust_escape(mpn)}\",")
        lines.append(f"                    manufacturer: \"{rust_escape(mfr)}\",")
        lines.append(f"                    lifecycle: {lifecycle_variant(lifecycle)},")
        lines.append(f"                    datasheet: \"{rust_escape(ds)}\",")
        lines.append(f"                }},")
    lines.append(f"            ],")
    return "\n".join(lines)

